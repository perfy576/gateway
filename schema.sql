CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 display_name VARCHAR(128) NOT NULL,
 password_hash VARCHAR(256) CHARACTER SET ascii NOT NULL,
 role ENUM('admin','user') NOT NULL DEFAULT 'user',
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 appid VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 name VARCHAR(128) NOT NULL,
 host VARCHAR(253) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 upstream VARCHAR(512) CHARACTER SET ascii NOT NULL,
 excluded_paths JSON NOT NULL,
 token_secret CHAR(64) CHARACTER SET ascii NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 allow_all BOOLEAN NOT NULL DEFAULT TRUE,
 cookie_max_age_seconds BIGINT UNSIGNED NOT NULL DEFAULT 43200,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS service_users (
 service_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(service_id,user_id),
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(64) NOT NULL,
 action VARCHAR(64) NOT NULL,
 detail VARCHAR(2048) NOT NULL,
 ip VARCHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at)
) ENGINE=InnoDB;
